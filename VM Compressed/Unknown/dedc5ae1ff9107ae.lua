do
    local screenGui = LMG2L["ScreenGui_1"]
    local portuguesBtn = LMG2L["Português_a"]
    local inglesBtn = LMG2L["Inglês_c"]
    local fecharBtn = LMG2L["Fechar_e"]
    local discordButton = LMG2L["ImageButton_14"] -- clickable area
    local discordLabel = LMG2L["TextLabel_18"] -- visual label (not clickable if TextLabel, but kept for safety)

    local DISCORD_URL = "https://discord.gg/wZhW2Uev6M"

    local function notify(title, text, duration)
        pcall(function()
            local starterGui = game:GetService("StarterGui")
            if starterGui and starterGui.SetCore then
                starterGui:SetCore("SendNotification", {
                    Title = title or "Notification",
                    Text = text or "",
                    Duration = duration or 3
                })
            end
        end)
    end

    -- tenta várias abordagens para copiar para a área de transferência:
    -- 1) função global setclipboard (comum em executores)
    -- 2) StarterGui:SetCore("CopyToClipboard", text) (pode existir em alguns contextos)
    local function copyToClipboard(text)
        -- tentativa 1: setclipboard (exploit executors)
        local ok, err
        if type(setclipboard) == "function" then
            ok, err = pcall(function() setclipboard(text) end)
            if ok then
                return true
            end
        end

        -- tentativa 2: StarterGui SetCore
        local starterGui = game:GetService("StarterGui")
        if starterGui and starterGui.SetCore then
            local suc, e = pcall(function()
                starterGui:SetCore("CopyToClipboard", text)
            end)
            if suc then
                return true
            else
                err = e
            end
        end

        -- nenhuma API disponível
        return false, err or "Clipboard API not available"
    end

    local function onDiscordClick()
        local success, err = copyToClipboard(DISCORD_URL)
        if success then
            notify("Copiado", "Convite do Discord copiado para a área de transferência.", 3)
        else
            warn("Não foi possível copiar o convite do Discord:", err)
            -- fallback: mostra notificação com o link para o usuário copiar manualmente
            notify("Copiar falhou", "Abra o chat ou cole manualmente: " .. DISCORD_URL, 6)
        end
    end

    if portuguesBtn and portuguesBtn:IsA("TextButton") then
        portuguesBtn.MouseButton1Click:Connect(function()
            -- Português - BR
            local ok, err = pcall(function()
                loadstring(game:HttpGet("https://raw.githubusercontent.com/phzlyp7-sys/7zRep/refs/heads/main/README.md"))()
            end)
            if not ok then
                warn("Falha ao carregar versão Português:", err)
            end
        end)
    end

    if inglesBtn and inglesBtn:IsA("TextButton") then
        inglesBtn.MouseButton1Click:Connect(function()
            -- Inglês
            local ok, err = pcall(function()
                loadstring(game:HttpGet("https://raw.githubusercontent.com/phzlyp7-sys/7zRep2/refs/heads/main/README.md"))()
            end)
            if not ok then
                warn("Falha ao carregar versão English:", err)
            end
        end)
    end

    if fecharBtn and fecharBtn:IsA("TextButton") then
        fecharBtn.MouseButton1Click:Connect(function()
            -- Fecha a UI sem remover elementos (desativa o ScreenGui)
            if screenGui then
                screenGui.Enabled = false
            end
        end)
    end

    -- Conectar cópia do convite ao clicar na área do botão (ImageButton)
    if discordButton and discordButton:IsA("ImageButton") then
        discordButton.MouseButton1Click:Connect(onDiscordClick)
    end

    -- Caso o rótulo seja alterado para TextButton, conecta também
    if discordLabel and discordLabel:IsA("TextButton") then
        discordLabel.MouseButton1Click:Connect(onDiscordClick)
    end
end

